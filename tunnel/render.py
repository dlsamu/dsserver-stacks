#!/usr/bin/python3 -I
"""Validate tunnel/routes.toml and render the cloudflared ingress config (stdlib only, offline).

  render.py --check                 validate; exit 1 on any problem
  render.py --tunnel-id <uuid>      print config.yml for cloudflared (enabled routes only; default 404)
"""
import argparse, re, sys, tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ZONE = "rubusdua.net"
ORIGIN = "https://proxy-caddy:443"
FORBIDDEN = re.compile(r"^(beacon|dsserver|ssh|admin|docker|portainer|grafana|beszel|caddy|nas|dataserver|router|deco)(\.|-|$)")
ACCESS = {"otp", "service-token", "public"}


def caddy_sites(caddyfile: Path) -> set:
    sites = set()
    for line in caddyfile.read_text().splitlines():
        m = re.match(r"^([A-Za-z0-9.,\s-]+)\{\s*$", line)
        if m and not line.startswith((" ", "\t")):
            sites |= {s.strip() for s in m.group(1).replace(",", " ").split() if "." in s}
    return sites


def problems(routes: list, sites: set) -> list:
    p, seen = [], set()
    for i, r in enumerate(routes):
        h = r.get("hostname", "")
        where = f"route {i + 1} ({h or '?'})"
        if not re.fullmatch(r"[a-z0-9-]+\." + re.escape(ZONE), h):
            p.append(f"{where}: hostname must be <name>.{ZONE}")
        elif FORBIDDEN.match(h):
            p.append(f"{where}: infrastructure names are never public")
        if h in seen:
            p.append(f"{where}: duplicate hostname")
        seen.add(h)
        if "service" in r and r["service"] != ORIGIN:
            p.append(f"{where}: service must be {ORIGIN} (all routes go through Caddy)")
        if h and h not in sites:
            p.append(f"{where}: no Caddy site block for {h} in proxy/Caddyfile")
        a = r.get("access")
        if a not in ACCESS:
            p.append(f"{where}: access must be one of {sorted(ACCESS)}")
        if a == "otp" and not r.get("allowed_emails"):
            p.append(f"{where}: access=otp needs allowed_emails")
        if a == "public" and not r.get("public_reason"):
            p.append(f"{where}: access=public needs public_reason")
        if not isinstance(r.get("enabled"), bool):
            p.append(f"{where}: enabled must be true or false")
        for bp in r.get("bypass_paths", []):
            if bp != r.get("health_path"):
                p.append(f"{where}: only the health_path may bypass Access ({bp})")
    return p


def render(routes: list, tunnel_id: str) -> str:
    if not re.fullmatch(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", tunnel_id):
        sys.exit("tunnel id must be a UUID")
    out = [f"# GENERATED by tunnel/render.py from routes.toml - do not edit", f"tunnel: {tunnel_id}",
           "credentials-file: /etc/cloudflared/credentials.json", "metrics: 127.0.0.1:2000", "no-autoupdate: true",
           "ingress:"]
    for r in routes:
        if r["enabled"]:
            out += [f"  - hostname: {r['hostname']}", f"    service: {ORIGIN}", "    originRequest:",
                    f"      originServerName: {r['hostname']}", "      connectTimeout: 10s"]
    out.append("  - service: http_status:404")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tunnel-id")
    ap.add_argument("--routes", default=str(HERE / "routes.toml"))
    ap.add_argument("--caddyfile", default=str(HERE.parent / "proxy" / "Caddyfile"))
    a = ap.parse_args()
    routes = tomllib.loads(Path(a.routes).read_text()).get("route", [])
    p = problems(routes, caddy_sites(Path(a.caddyfile)))
    if p:
        print("\n".join("FAIL  " + x for x in p))
        sys.exit(1)
    if a.check or not a.tunnel_id:
        en = [r["hostname"] for r in routes if r["enabled"]]
        print(f"routes.toml ok: {len(routes)} route(s), enabled: {', '.join(en) or 'none'}")
        return
    sys.stdout.write(render(routes, a.tunnel_id))


if __name__ == "__main__":
    main()
