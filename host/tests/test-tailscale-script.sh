#!/bin/bash
# Tests for host/scripts/11-tailscale.sh without root and without changing the system:
# syntax, argument handling, and the pure check helpers (key fingerprint, prefs, routes, DNS, sockets).
# Needs network access once to fetch Tailscale's public repository key; skips that check offline.
set -uo pipefail
HERE=$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")
S=$HERE/../scripts/11-tailscale.sh
pass=0; failn=0
t() { local name=$1; shift; if "$@" >/dev/null 2>&1; then echo "pass  $name"; pass=$((pass+1)); else echo "FAIL  $name"; failn=$((failn+1)); fi; }
not() { ! "$@"; }
eq() { [ "$1" = "$2" ]; }

t "bash syntax" bash -n "$S"
out=$(bash "$S" 2>&1); rc=$?;            t "no argument -> usage, exit 2" eq "$rc" 2
out=$(bash "$S" bogus 2>&1); rc=$?;      t "unknown step -> exit 2" eq "$rc" 2
out=$(bash "$S" install extra 2>&1); rc=$?; t "extra argument -> exit 2" eq "$rc" 2
out=$(bash "$S" verify 2>&1); rc=$?;     t "non-root -> refused" eq "$rc" 1
t "non-root message" grep -q "run with sudo" <<<"$out"

# shellcheck source=../scripts/11-tailscale.sh
. "$S"   # main() is not run when sourced
set +e

W=$(mktemp -d); trap 'rm -rf "$W"' EXIT

# --- signing key
if curl -fsSL --max-time 20 https://pkgs.tailscale.com/stable/debian/trixie.noarmor.gpg -o "$W/ts.gpg"; then
    t "Tailscale repository key verifies" key_ok "$W/ts.gpg"
else
    echo "skip  Tailscale repository key (offline)"
fi
t "Docker key is rejected" not key_ok /etc/apt/keyrings/docker.asc
echo garbage >"$W/junk"; t "garbage key file is rejected" not key_ok "$W/junk"

# --- prefs
good='{"WantRunning":true,"Hostname":"dsserver","CorpDNS":false,"RouteAll":false,"RunSSH":false,"ShieldsUp":true,"ExitNodeID":"","ExitNodeIP":"","AdvertiseRoutes":null}'
t "approved prefs -> no problems" eq "$(prefs_problems <<<"$good")" ""
for mod in '.CorpDNS=true' '.RouteAll=true' '.RunSSH=true' '.ShieldsUp=false' '.Hostname="dsserver-1"' \
           '.ExitNodeID="nX"' '.AdvertiseRoutes=["192.168.68.0/24"]' '.AdvertiseRoutes=["0.0.0.0/0","::/0"]' \
           '.WantRunning=false' 'del(.CorpDNS)' '.AdvertiseServices=["svc:x"]'; do
    p=$(jq -c "$mod" <<<"$good" | prefs_problems)
    t "prefs deviation detected: $mod" not eq "$p" ""
done

# --- routes
r='[{"dst":"100.100.100.100","dev":"tailscale0"},{"dst":"100.81.116.21","dev":"tailscale0"},{"dst":"100.64.0.0/10","dev":"tailscale0"},{"dst":"fd7a:115c:a1e0::/48","dev":"tailscale0"}]'
t "tailnet-only routes accepted" eq "$(routes_outside_tailnet <<<"$r")" ""
t "default route flagged" eq "$(routes_outside_tailnet <<<'[{"dst":"default","dev":"tailscale0"}]')" "default"
t "LAN prefix flagged" eq "$(routes_outside_tailnet <<<'[{"dst":"192.168.68.0/24","dev":"tailscale0"}]')" "192.168.68.0/24"
t "wider-than-tailnet flagged" eq "$(routes_outside_tailnet <<<'[{"dst":"100.0.0.0/8"}]')" "100.0.0.0/8"
t "empty table ok" eq "$(routes_outside_tailnet <<<'[]')" ""
t "current main table parses" eval 'ip -j route show table main | routes_outside_tailnet >/dev/null'

# --- resolv.conf
t "NetworkManager resolv.conf not flagged" not resolv_touched <<<$'# Generated by NetworkManager\nnameserver 2.248.248.2'
t "MagicDNS resolver flagged" resolv_touched <<<$'nameserver 100.100.100.100'
t "Tailscale search domain flagged" resolv_touched <<<$'search tail96c1da.ts.net'
t "current /etc/resolv.conf not flagged" not resolv_touched </etc/resolv.conf

# --- sockets
printf '%s\n' 'tcp 0.0.0.0:22 users:(("sshd"))' 'udp 0.0.0.0:5353 users:(("avahi-daemon"))' | sort >"$W/b"
printf '%s\n' 'tcp 0.0.0.0:22 users:(("sshd"))' 'udp 0.0.0.0:5353 users:(("avahi-daemon"))' \
              'udp 0.0.0.0:41641 users:(("tailscaled"))' 'tcp 100.70.1.2:44123 users:(("tailscaled"))' | sort >"$W/a1"
t "only tailscaled sockets -> nothing reported" eq "$(new_sockets "$W/b" "$W/a1" | sockets_not_tailscaled)" ""
printf '%s\n' 'tcp 0.0.0.0:22 users:(("sshd"))' 'tcp 0.0.0.0:8080 users:(("python3"))' | sort >"$W/a2"
t "other new socket reported" eq "$(new_sockets "$W/b" "$W/a2" | sockets_not_tailscaled)" 'tcp 0.0.0.0:8080 users:(("python3"))'
t "listen() strips pid/fd" eval "echo 'tcp LISTEN 0 128 0.0.0.0:22 0.0.0.0:* users:((\"sshd\",pid=812,fd=6))' | awk '{p=\$7; gsub(/,pid=[0-9]+,fd=[0-9]+/, \"\", p); print \$1, \$5, p}' | grep -qx 'tcp 0.0.0.0:22 users:((\"sshd\"))'"

# --- approved flags
flags=" ${UP_FLAGS[*]} "
for f in --hostname=dsserver --accept-dns=false --accept-routes=false --ssh=false --shields-up --advertise-exit-node=false; do
    t "up flag present: $f" grep -q -- " $f " <<<"$flags"
done
t "no --ssh=true / --advertise-exit-node=true" not grep -qE -- '--ssh( |=true)|--advertise-exit-node( |=true)' <<<"$flags"
t "sources file uses the pinned keyring" grep -qx 'Signed-By: /usr/share/keyrings/tailscale-archive-keyring.gpg' <<<"$SOURCES_CONTENT"

echo; echo "$pass passed, $failn failed"
[ "$failn" = 0 ]
